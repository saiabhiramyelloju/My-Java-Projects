class Operators
{
    public static void main(String args[])
    {
        int a = 10;
        int b = 20;
        System.out.println("Arthematic Operators");
        System.out.println(a + b);
        System.out.println(a - b);
        System.out.println(a * b);
        System.out.println(a / b);
        System.out.println(a % b);
        System.out.println("");
        System.out.println("Relational Operators");
        System.out.println(a > b);
        System.out.println(a < b);
        System.out.println(a >= b);
        System.out.println(a <= b);
        System.out.println(a == b);
        System.out.println(a != b);
        System.out.println("");
        System.out.println("Logical Operators");
        boolean x = true;
        boolean y = false;
        System.out.println(x & y);
        System.out.println(x | y);
        System.out.println(x ^ y);
    }
}